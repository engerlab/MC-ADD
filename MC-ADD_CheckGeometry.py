# ::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
# This Python script inspects the DetectorConstruction.cc file and verifies if the user code is ready for compilation.
# The script is divided into 3 main sections:
#
#   1) Reading the DetectorConstruction.cc: The comments of the C++ code are removed so that only the active (uncommented)
#                                           lines of code are analysed.
#
#   2) Verification: The source, detector, and Meshgeometries are identified, together with their shape, dimensions,
#                    materials, and positions. If a Meshgeometry is defined as the sensitive volume, it is also reported.
#
#   3) Report: A summary of the geometry, the warnings, and the errors is printed in the terminal and saved in the
#              MC-ADD_GeometryReport.txt file.
#
# Important Notes!:
#       - This script is executed automatically by the GUI each time the geometry is saved.
#       - This script can be executed as many times as needed. For example, after modifying the DetectorConstruction.cc
#         to add Meshgeometries. To run it, use the following command in the terminal:
#
#                   python3 MC-ADD_CheckGeometry.py
#
#         By default, the script reads the src/DetectorConstruction.cc file. To verify another file, use:
#
#                   python3 MC-ADD_CheckGeometry.py path/to/DetectorConstruction.cc
#
#       - This script does NOT compile the code. Compilation errors must still be checked when compiling the Geant4 app.
#
# Author: Víctor Daniel Díaz Martínez
# ::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::


# :::::: We import the needed libraries ::::::
import os
import re
import sys

# ::: Important paths :::
BASE_DIR   = os.path.dirname(os.path.abspath(__file__))                                # Obtaining the main path (same level where this script should be)
CCFile     = os.path.join(BASE_DIR, "src", "DetectorConstruction.cc")                  # Default DetectorConstruction.cc file to be verified
ReportFile = os.path.join(BASE_DIR, "MC-ADD_GeometryReport.txt")                       # Report generated by this script

# ::: Patterns used to identify numbers and units :::
NUMBER = r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?"                                            # Any number (e.g. 10, 0.5, 1.08e-6)
UNIT   = r"(?:nm|um|mm|cm|m)"                                                          # Length units used in the DetectorConstruction.cc


# ::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
# :::                                                                :::
# :::   R E A D I N G   T H E   D E T E C T O R   C O N S T R .      :::
# :::                                                                :::
# ::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::

def remove_comments(code):

    # :::::: Removing // and /* */ comments while keeping the text inside quotes ::::::
    ActiveCode = []
    i = 0
    InString = False

    while i < len(code):

        char = code[i]

        if InString:                                                                    # Inside a string ("..."), everything is kept
            ActiveCode.append(char)
            if char == '"' and code[i-1] != "\\":
                InString = False
            i += 1

        elif char == '"':                                                               # Beginning of a string
            InString = True
            ActiveCode.append(char)
            i += 1

        elif code.startswith("//", i):                                                  # Line comment: skip up to the end of the line
            EndLine = code.find("\n", i)
            if EndLine == -1:
                break
            i = EndLine

        elif code.startswith("/*", i):                                                  # Block comment: skip up to */
            EndBlock = code.find("*/", i + 2)
            if EndBlock == -1:
                ActiveCode.append("\n__UNCLOSED_BLOCK_COMMENT__\n")                     # Flag for a /* without its closing */
                break
            ActiveCode.append("\n" * code.count("\n", i, EndBlock))                     # Keep the line breaks
            i = EndBlock + 2

        else:
            ActiveCode.append(char)
            i += 1

    return "".join(ActiveCode)



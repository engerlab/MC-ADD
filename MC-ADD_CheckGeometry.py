def check_geometry(FilePath):

    Report   = []                                                                       # Summary of the geometry
    Warnings = []                                                                       # Issues that do not prevent the compilation
    Errors   = []                                                                       # Issues that must be solved before compiling

    # :::::: Reading the DetectorConstruction.cc ::::::
    if not os.path.isfile(FilePath):
        Errors.append(f"The file {FilePath} was not found.")
        return Report, Warnings, Errors

    with open(FilePath, "r") as cc_file:
        RawCode = cc_file.read()

    ActiveCode = remove_comments(RawCode)                                               # Only the uncommented lines are analysed
    Variables  = get_variables(ActiveCode)

    if "__UNCLOSED_BLOCK_COMMENT__" in ActiveCode:
        Errors.append("A block comment (/*) was opened but never closed (*/). Check the Meshgeometries section.")


    # ::::::::::::::::::::::::::::::
    # :::  Source and Detector   :::
    # ::::::::::::::::::::::::::::::

    Source   = get_primitive(ActiveCode, Variables, "Source", "Pos2")
    Detector = get_primitive(ActiveCode, Variables, "Detector", "Pos3")

    Report.append("Geometries defined by the user:")

    for VolumeName, Volume in [("Source", Source), ("Detector", Detector)]:
        if Volume["Defined"]:
            Report.append(f"  {VolumeName}:")
            Report.append(f"      Shape:      {Volume['Shape']}")
            Report.append(f"      Dimensions: {Volume['Dimensions']}")
            Report.append(f"      Material:   {Volume['Material']}")
            Report.append(f"      Position:   {Volume['Position']}")
        else:
            Report.append(f"  {VolumeName}: Not defined (or commented)")


    # ::::::::::::::::::::::::::::::
    # :::     Meshgeometries     :::
    # ::::::::::::::::::::::::::::::

    MeshPattern = r"(mesh\d+)\s*=\s*CADMesh::TessellatedMesh::From(STL|OBJ)\(\s*(?:basePath\s*\+\s*)?\"([^\"]+)\""

    # ::: Active (uncommented) Meshgeometries :::
    ActiveMeshes = {}
    for MeshVariable, MeshFormat, MeshFile in re.findall(MeshPattern, ActiveCode):
        if MeshVariable in ActiveMeshes:
            Errors.append(f"{MeshVariable} is imported more than once. Uncomment only the STL or the OBJ line, not both.")
        ActiveMeshes[MeshVariable] = (MeshFormat, MeshFile)

    # ::: All Meshgeometries written in the file (active or commented). The examples of the instructions are excluded :::
    AllMeshes = [MeshFile for MeshVariable, MeshFormat, MeshFile in re.findall(MeshPattern, RawCode)
                 if MeshFile not in ("NAME.obj", "Name.stl")]
    DisabledMeshes = sorted({os.path.splitext(MeshFile)[0] for MeshFile in AllMeshes}
                            - {os.path.splitext(MeshFile)[0] for MeshFormat, MeshFile in ActiveMeshes.values()})

    # ::: Mesh variables used without being imported (e.g. the FromSTL line is still commented) :::
    for MeshVariable in sorted(set(re.findall(r"\b(mesh\d+)->", ActiveCode))):
        if MeshVariable not in ActiveMeshes:
            Errors.append(f"{MeshVariable} is used, but its import line (FromSTL or FromOBJ) is commented.")

    # ::: Solids and logical volumes of the active Meshgeometries :::
    MeshSolids = {}                                                                     # Solid name --> mesh file
    for SolidName, MeshVariable in re.findall(r"auto\s+(\w+)\s*=\s*(mesh\d+)->GetSolid\(\)", ActiveCode):
        if MeshVariable in ActiveMeshes:
            MeshSolids[SolidName] = ActiveMeshes[MeshVariable][1]

    MeshLogicals  = {}                                                                  # Logical volume --> mesh file
    MeshMaterials = {}                                                                  # Mesh file --> material
    for LogicalName, SolidName, MaterialVariable in re.findall(r"(\w+)\s*=\s*new\s+G4LogicalVolume\(\s*(\w+)\s*,\s*(\w+)", ActiveCode):
        if SolidName in MeshSolids:
            MeshLogicals[LogicalName] = MeshSolids[SolidName]
            MeshName = os.path.splitext(MeshSolids[SolidName])[0]
            if MaterialVariable == "MATERIAL":
                MeshMaterials[MeshSolids[SolidName]] = "Not defined"
                Errors.append(f"The material of the Meshgeometry {MeshName} is not defined (MATERIAL must be replaced).")
            else:
                MeshMaterials[MeshSolids[SolidName]] = get_material(ActiveCode, MaterialVariable)

    # ::: Report of the Meshgeometries :::
    if ActiveMeshes:
        Report.append(f"  Meshgeometries: Defined ({len(ActiveMeshes)})")
        for MeshVariable, (MeshFormat, MeshFile) in ActiveMeshes.items():
            Report.append(f"      - {MeshFile} (Material: {MeshMaterials.get(MeshFile, 'Not found')})")
    else:
        Report.append("  Meshgeometries: Not defined")

    if DisabledMeshes:
        Warnings.append("The DetectorConstruction.cc contains Meshgeometries that are not enabled "
                        "(commented) and whose materials may not be defined yet: " + ", ".join(DisabledMeshes) + ".")


    # ::::::::::::::::::::::::::::::
    # :::   Meshfiles folder     :::
    # ::::::::::::::::::::::::::::::

    BasePathMatch = re.search(r"std::string\s+basePath\s*=\s*\"([^\"]*)\"", ActiveCode)

    if ActiveMeshes and not BasePathMatch:
        Errors.append("The Meshfiles folder path (basePath) is not enabled. Uncomment the basePath line for STL or OBJ files.")

    elif not ActiveMeshes and DisabledMeshes:
        Warnings.append("The Meshfiles folder path (basePath) is not enabled.")

    if ActiveMeshes and BasePathMatch:
        BasePath = BasePathMatch.group(1)

        if not os.path.isdir(BasePath):
            Errors.append(f"The Meshfiles folder was not found: {BasePath}")

        else:
            for MeshVariable, (MeshFormat, MeshFile) in ActiveMeshes.items():
                MeshPath = BasePath + MeshFile

                if not os.path.isfile(MeshPath):
                    Errors.append(f"The Meshfile was not found: {MeshPath}")

                elif MeshFormat == "STL":                                               # CADMesh built-in reader requires ASCII STL files
                    with open(MeshPath, "rb") as mesh_file:
                        Header = mesh_file.read(2048)
                    if not (Header.lstrip().startswith(b"solid") and b"facet" in Header):
                        Errors.append(f"The Meshfile {MeshFile} is not saved in ASCII STL format.")


    # ::::::::::::::::::::::::::::::
    # :::   Sensitive volume     :::
    # ::::::::::::::::::::::::::::::

    SensitiveLogicals = re.findall(r"(\w+)->SetSensitiveDetector\(", ActiveCode)

    if not SensitiveLogicals:
        Errors.append("No sensitive volume was found (SetSensitiveDetector is missing in ConstructSDandField).")

    for LogicalName in SensitiveLogicals:

        if LogicalName == "Detector_log":                                               # The last definition of Detector_log is the one used
            DetectorLogicals = re.findall(r"\bDetector_log\s*=\s*new\s+G4LogicalVolume\(\s*(\w+)", ActiveCode)

            if DetectorLogicals and DetectorLogicals[-1] in MeshSolids:
                MeshName = os.path.splitext(MeshSolids[DetectorLogicals[-1]])[0]
                Report.append(f"  Sensitive volume: Meshgeometry {MeshName}")
                Report.append(f"  >>> The CADMesh geometry {MeshName} has been defined as a sensitive volume.")

                if Detector["Defined"] and re.search(r"Detector_phys\s*=\s*new\s+G4PVPlacement", ActiveCode):
                    Warnings.append("The GUI-defined Detector is still placed in the geometry, although the sensitive volume "
                                    "is a Meshgeometry. Check that both volumes do not overlap.")

            elif not DetectorLogicals:
                Errors.append("Detector_log is defined as sensitive volume, but its logical volume was not found.")

        elif LogicalName in MeshLogicals:                                               # A Meshgeometry logical volume defined directly as sensitive
            MeshName = os.path.splitext(MeshLogicals[LogicalName])[0]
            Report.append(f"  Sensitive volume: Meshgeometry {MeshName}")
            Report.append(f"  >>> The CADMesh geometry {MeshName} has been defined as a sensitive volume.")

    return Report, Warnings, Errors


# ::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
# :::                                                                :::
# :::                         R E P O R T                            :::
# :::                                                                :::
# ::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::

def write_report(FilePath):

    Report, Warnings, Errors = check_geometry(FilePath)

    Lines = []
    Lines.append(":::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::")
    Lines.append(":::                  MC-ADD Geometry Verification Report                  :::")
    Lines.append(":::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::")
    Lines.append(f"File: {FilePath}")
    Lines.append("")
    Lines.extend(Report)
    Lines.append("")

    # ::: Warnings :::
    for warning in Warnings:
        Lines.append(f"WARNING: {warning}")

    # ::: Errors :::
    for error in Errors:
        Lines.append(f"ERROR: {error}")

    if Warnings or Errors:
        Lines.append("")

    # ::: Final status (any warning or error means that the user code is not ready) :::
    if Errors or Warnings:
        Lines.append("The user code is not ready for compilation.")
    else:
        Lines.append("The user code is ready for compilation.")

    Lines.append(":::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::")

    ReportText = "\n".join(Lines)

    print(ReportText)                                                                   # Printing the report in the terminal

    with open(ReportFile, "w") as report_file:                                          # Saving the report
        report_file.write(ReportText + "\n")

    return not (Errors or Warnings)



def get_variables(code):

    # :::::: Collecting all the G4double variables (e.g. G4double SourceX = 10/2.*mm;) ::::::
    Variables = {}

    for name, value in re.findall(r"G4double\s+(\w+)\s*=\s*([^;]+);", code):
        Variables[name] = value.strip()

    return Variables


def full_length(expression):

    # :::::: Geant4 uses half-lengths. This function returns the full length defined by the user ::::::
    expression = expression.strip()

    HalfMatch = re.fullmatch(rf"({NUMBER})\s*/\s*2\.?0*\s*\*\s*({UNIT})", expression)   # e.g. 10/2.*mm --> 10 mm
    if HalfMatch:
        return f"{HalfMatch.group(1)} {HalfMatch.group(2)}"

    ValueMatch = re.fullmatch(rf"({NUMBER})\s*\*\s*({UNIT})", expression)              # e.g. 5*mm (half-length) --> 10 mm
    if ValueMatch:
        return f"{2*float(ValueMatch.group(1)):g} {ValueMatch.group(2)}"

    return f"2 x ({expression})"                                                        # Expression that could not be simplified


def length(expression):

    # :::::: Returns a length (e.g. a radius) in a readable format ::::::
    expression = expression.strip()

    ValueMatch = re.fullmatch(rf"({NUMBER})\s*\*\s*({UNIT})", expression)              # e.g. 2.5*mm --> 2.5 mm
    if ValueMatch:
        return f"{ValueMatch.group(1)} {ValueMatch.group(2)}"

    return expression


def get_material(code, MaterialVariable):

    # :::::: Finding the name of the material assigned to a logical volume ::::::
    NistMatch = re.search(rf"\b{MaterialVariable}\s*=\s*nist->FindOrBuildMaterial\(\s*\"([^\"]+)\"", code)
    if NistMatch:
        return NistMatch.group(1)                                                       # Material from the Geant4 material database

    UserMatch = re.search(rf"\b{MaterialVariable}\s*=\s*new\s+G4Material\(\s*\"([^\"]+)\"", code)
    if UserMatch:
        return UserMatch.group(1) + " (user-defined)"                                   # Material defined by the user

    return MaterialVariable


def get_position(code, PositionVariable):

    # :::::: Finding the position of a volume (e.g. Pos2 = G4ThreeVector(0*mm, 0*mm, 0*mm);) ::::::
    PositionMatch = re.search(rf"\b{PositionVariable}\s*=\s*G4ThreeVector\(([^;]*)\)\s*;", code)
    if not PositionMatch:
        return "Not found"

    Coordinates = [value.strip().replace("*", " ") for value in PositionMatch.group(1).split(",")]
    return "(" + ", ".join(Coordinates) + ")"


def get_primitive(code, Variables, VolumeName, PositionVariable):

    # :::::: Identifying a GUI-defined volume (Source or Detector): shape, dimensions, material, and position ::::::
    Volume = {"Defined": False}

    ShapeMatch = re.search(rf"new\s+G4(Box|Tubs)\s*\(\s*\"{VolumeName}\"\s*,([^;]*)\)\s*;", code)
    if not ShapeMatch:
        return Volume

    Volume["Defined"] = True
    Arguments = [argument.strip() for argument in ShapeMatch.group(2).split(",")]

    # ::: Shape and dimensions :::
    if ShapeMatch.group(1) == "Box":                                                    # For Box
        Dimensions = [full_length(Variables.get(argument, argument)) for argument in Arguments[0:3]]
        Volume["Shape"] = "Box"
        Volume["Dimensions"] = f"x = {Dimensions[0]}, y = {Dimensions[1]}, z = {Dimensions[2]}"

    elif ShapeMatch.group(1) == "Tubs":                                                 # For Cylinder
        InnerRadius = length(Variables.get(Arguments[0], Arguments[0]))
        OuterRadius = length(Variables.get(Arguments[1], Arguments[1]))
        Thickness   = full_length(Variables.get(Arguments[2], Arguments[2]))
        Volume["Shape"] = "Cylinder"
        Volume["Dimensions"] = f"inner radius = {InnerRadius}, outer radius = {OuterRadius}, thickness = {Thickness}"

    # ::: Material :::
    LogicalMatch = re.search(rf"\b{VolumeName}_log\s*=\s*new\s+G4LogicalVolume\(\s*{VolumeName}\s*,\s*(\w+)", code)
    Volume["Material"] = get_material(code, LogicalMatch.group(1)) if LogicalMatch else "Not found"

    # ::: Position :::
    Volume["Position"] = get_position(code, PositionVariable)

    return Volume



if __name__ == "__main__":

    if len(sys.argv) > 1:                                                               # A specific DetectorConstruction.cc file was given
        FileToCheck = sys.argv[1]
    else:                                                                               # Default: src/DetectorConstruction.cc
        FileToCheck = CCFile

    IsReady = write_report(FileToCheck)
    sys.exit(0 if IsReady else 1)